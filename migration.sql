-- roomchat public-room chat schema. No user profile or persistent nickname table is created.
create table if not exists public.rooms (
  id uuid primary key default gen_random_uuid(),
  name text not null unique check (char_length(name) between 2 and 32),
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.rooms(id) on delete cascade,
  nickname text not null check (char_length(nickname) between 1 and 24),
  content text check (content is null or char_length(content) <= 2000),
  image_path text,
  created_at timestamptz not null default now(),
  constraint messages_need_content_or_image check (
    (content is not null and char_length(btrim(content)) > 0) or image_path is not null
  )
);
create index if not exists messages_room_created_idx on public.messages (room_id, created_at);

alter table public.rooms enable row level security;
alter table public.messages enable row level security;

drop policy if exists "roomchat rooms are readable" on public.rooms;
create policy "roomchat rooms are readable" on public.rooms for select to anon using (true);
drop policy if exists "roomchat anyone can create rooms" on public.rooms;
create policy "roomchat anyone can create rooms" on public.rooms for insert to anon with check (char_length(name) between 2 and 32);
drop policy if exists "roomchat messages are readable" on public.messages;
create policy "roomchat messages are readable" on public.messages for select to anon using (true);
drop policy if exists "roomchat anyone can post messages" on public.messages;
create policy "roomchat anyone can post messages" on public.messages for insert to anon with check (
  char_length(nickname) between 1 and 24
  and (content is null or char_length(content) <= 2000)
  and ((content is not null and char_length(btrim(content)) > 0) or image_path is not null)
);

grant select, insert on public.rooms to anon;
grant select, insert on public.messages to anon;
grant usage, select on sequence public.messages_id_seq to anon;

-- Seed one room so the UI has somewhere to start.
insert into public.rooms (name) values ('라운지') on conflict (name) do nothing;

-- Add tables to Supabase Realtime only when they are not already published.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
  if not exists (
    select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'rooms'
  ) then
    alter publication supabase_realtime add table public.rooms;
  end if;
end $$;

-- Images are publicly viewable in rooms. Anonymous uploads are restricted to the dedicated bucket.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('chat-images', 'chat-images', true, 8388608, array['image/jpeg','image/png','image/webp','image/gif','image/avif'])
on conflict (id) do update set public = true, file_size_limit = 8388608,
  allowed_mime_types = array['image/jpeg','image/png','image/webp','image/gif','image/avif'];

drop policy if exists "roomchat public image read" on storage.objects;
create policy "roomchat public image read" on storage.objects for select to anon using (bucket_id = 'chat-images');
drop policy if exists "roomchat anonymous image upload" on storage.objects;
create policy "roomchat anonymous image upload" on storage.objects for insert to anon with check (bucket_id = 'chat-images');
