-- Applied migration: roomchat_dm_replies_and_reports
-- Adds message reply references and a private report intake workflow.
ALTER TABLE public.roomchat_dms
  ADD COLUMN IF NOT EXISTS reply_to bigint REFERENCES public.roomchat_dms(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS roomchat_dms_reply_to_idx ON public.roomchat_dms(reply_to);

CREATE TABLE IF NOT EXISTS public.roomchat_dm_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  message_id bigint NOT NULL REFERENCES public.roomchat_dms(id) ON DELETE CASCADE,
  reason text NOT NULL CHECK (reason IN ('spam','harassment','inappropriate','scam','other')),
  details text NOT NULL DEFAULT '' CHECK (char_length(details) <= 500),
  created_at timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','reviewing','resolved','dismissed')),
  UNIQUE (reporter, message_id)
);
ALTER TABLE public.roomchat_dm_reports ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.roomchat_dm_reports FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public.roomchat_send_dm_reply(p_to uuid, p_content text, p_reply_to bigint)
RETURNS public.roomchat_dms LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $function$
DECLARE
  v_me uuid := auth.uid();
  v_content text := nullif(btrim(coalesce(p_content, '')), '');
  v_original public.roomchat_dms%ROWTYPE;
  v_row public.roomchat_dms%ROWTYPE;
BEGIN
  IF v_me IS NULL THEN RAISE EXCEPTION '계정 로그인이 필요합니다.'; END IF;
  IF v_content IS NULL THEN RAISE EXCEPTION '메시지를 입력해 주세요.'; END IF;
  IF char_length(v_content) > 2000 THEN RAISE EXCEPTION '메시지는 2000자 이내로 입력해 주세요.'; END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.roomchat_friendships f WHERE f.status='accepted'
      AND ((f.requester=v_me AND f.addressee=p_to) OR (f.requester=p_to AND f.addressee=v_me))
  ) THEN RAISE EXCEPTION '친구끼리만 DM을 보낼 수 있어요.'; END IF;
  SELECT * INTO v_original FROM public.roomchat_dms d
    WHERE d.id=p_reply_to
      AND ((d.sender=v_me AND d.recipient=p_to) OR (d.sender=p_to AND d.recipient=v_me));
  IF NOT FOUND THEN RAISE EXCEPTION '답장할 메시지를 찾을 수 없어요.'; END IF;
  INSERT INTO public.roomchat_dms(sender,recipient,content,reply_to)
    VALUES(v_me,p_to,v_content,p_reply_to) RETURNING * INTO v_row;
  RETURN v_row;
END
$function$;

CREATE OR REPLACE FUNCTION public.roomchat_report_dm(p_message_id bigint, p_reason text, p_details text DEFAULT '')
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $function$
DECLARE
  v_me uuid := auth.uid();
  v_report_id bigint;
  v_reason text := lower(btrim(coalesce(p_reason,'')));
  v_details text := left(btrim(coalesce(p_details,'')),500);
BEGIN
  IF v_me IS NULL THEN RAISE EXCEPTION '계정 로그인이 필요합니다.'; END IF;
  IF v_reason NOT IN ('spam','harassment','inappropriate','scam','other') THEN RAISE EXCEPTION '신고 사유를 선택해 주세요.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.roomchat_dms WHERE id=p_message_id AND recipient=v_me) THEN
    RAISE EXCEPTION '받은 DM만 신고할 수 있어요.';
  END IF;
  INSERT INTO public.roomchat_dm_reports(reporter,message_id,reason,details)
    VALUES(v_me,p_message_id,v_reason,v_details)
    ON CONFLICT (reporter,message_id) DO NOTHING RETURNING id INTO v_report_id;
  IF v_report_id IS NULL THEN RAISE EXCEPTION '이 메시지는 이미 신고했어요.'; END IF;
  RETURN v_report_id;
END
$function$;
REVOKE ALL ON FUNCTION public.roomchat_send_dm_reply(uuid,text,bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.roomchat_send_dm_reply(uuid,text,bigint) TO authenticated;
REVOKE ALL ON FUNCTION public.roomchat_report_dm(bigint,text,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.roomchat_report_dm(bigint,text,text) TO authenticated;
